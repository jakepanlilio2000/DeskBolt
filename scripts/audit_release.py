"""Check packaged desktop binaries for development entry points and markers."""

import argparse
import os
from pathlib import Path
import re
import subprocess


MARKERS = (
    "--mcp",
    "--loopback-only",
    "dev-mcp",
    "protocolchecks",
    "test_auth_handshake",
    "test_pty_roundtrip",
    "test_file_sync_roundtrip",
    "test_tunnel_and_sysinfo",
    "test_comms_and_power_sim",
    "simulatepoweraction",
    "simulated power action",
    "loopback protocol check",
    "the fixture listener requires",
    "topsecret!2026",
    "deskbolt_pty_check",
    "deskbolt_pty_roundtrip",
    "test mode",
    "production mode",
    "release mode",
    "artificial intelligence",
    "openai",
    "chatgpt",
    "generated by ai",
)
CLI_MARKERS = re.compile(rb"\bmcp\b|\bai\b|deskbolt_(?:viewer|server|proto)", re.I)


def audit(executable, title):
    data = executable.read_bytes().lower()
    for marker in MARKERS:
        if marker.encode("ascii") in data or marker.encode("utf-16-le") in data:
            raise ValueError(f"{executable}: found {marker!r} in the binary")

    for option, code, expected in (
        ("--help", 0, title.encode("ascii")),
        ("--mcp", 2, b"Unknown option"),
        ("--loopback-only", 2, b"Unknown option"),
    ):
        result = subprocess.run(
            [str(executable), option],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=10,
            check=False,
        )
        if result.returncode != code or expected not in result.stdout:
            raise ValueError(f"{executable} {option}: exit {result.returncode}, {result.stdout!r}")
        if CLI_MARKERS.search(result.stdout) or any(
            marker.encode("ascii") in result.stdout.lower() for marker in MARKERS
        ):
            raise ValueError(f"{executable} {option}: found development terminology")
        if option == "--help":
            print(result.stdout.decode().rstrip())
    print(f"{executable.name}: binary and CLI audit passed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release_dir", type=Path)
    args = parser.parse_args()
    suffix = ".exe" if os.name == "nt" else ""
    for binary, title in (("deskbolt-viewer", "DeskBolt Viewer"), ("deskbolt-server", "DeskBolt Host")):
        try:
            audit(args.release_dir.resolve() / f"{binary}{suffix}", title)
        except (OSError, ValueError, subprocess.TimeoutExpired) as error:
            parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
